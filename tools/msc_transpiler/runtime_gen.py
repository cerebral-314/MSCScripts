"""Writes scripts/angelscript/runtime/LegacyApi.txt from mapping.py.

Every line declares one function converted scripts call and the .script command or $function
it runs (the engine registers each line; see ASLegacyApi.h in the engine):

    void PlaySound(int channel, const ?&in ...) | command playsound {1} {...}
    string NameOf(const ?&in entity) | function get {1} name

The engine runs the same C++ handler the .script line would, with one argument per .script token,
so a converted call behaves exactly like the line it replaces. Arguments of any type are written
as .script text (Legacy.as Text() rules; entities as their id), so callers pass numbers, vectors
and entities as they are.
"""

from __future__ import annotations

from pathlib import Path

from . import mapping

GENERATED = "// Generated by msc_transpiler (runtime_gen.py) from mapping.py - edit mapping.py, not this file."

HEADER = """\
// The .script commands and $functions converted scripts call. The engine registers every line as a
// global function (visible to converted scripts only) that runs the legacy handler:
//
//     <declaration> | <kind> <name> <arguments>
//
// kind: command (a .script command), function ($name, its result read as the return type),
// eval (a token such as game.time), output (a command that writes its result into a variable),
// local / var (set an event local / a script variable), event (callevent), call ($func).
// Arguments: {n} is parameter n, {n.x} a vector component, {...} the variadic arguments.
// `const ?&in` takes a value of any type: entities (or their id text, or names such as ent_me),
// numbers, vectors and text are all passed the way .script would write them."""

# Things every converted script uses that are not in mapping.py's tables
GENERAL = [
    ("Events", [
        ("callevent <name> [params] - runs every handler of that event in this script",
         "void CallEvent(const string &in name, const ?&in ...)", "event {1} {...}"),
        ("callevent <value> ...: a number delays the call, anything else is the event name",
         "void CallEventOrDelay(const ?&in first, const ?&in ...)", "command callevent {1} {...}"),
        ("callexternal <target> <name> [params] - an event on another entity's scripts (or all, players, gamemaster)",
         "void CallExternal(const ?&in target, const string &in name, const ?&in ...)",
         "command callexternal {1} {2} {...}"),
        ("$func(<name>, params...) - what the event returns",
         "string CallFunction(const string &in name, const ?&in ...)", "call {1} {...}"),
    ]),
    ("Variables by .script name", [
        ("setvard <name> <value> - a variable that is not a field (set at run time, or by name)",
         "void SetVar(const string &in name, const ?&in value)", "var {1} {2}"),
        ("setvarg <name> <value> - a variable shared by every script on the server",
         "void SetGlobal(const string &in name, const ?&in value)", "command setvarg {1} {2}"),
        ("local reg.* values read by commands such as registerrace",
         "void SetLocal(const string &in name, const ?&in value)", "local {1} {2}"),
    ]),
    ("Entities", [
        ("$get(<entity>,<property>[,<option>...])",
         "string GetProp(const ?&in entity, const string &in prop, const ?&in ...)", "function get {1} {2} {...}"),
    ]),
    ("Anything without a function of its own", [
        ("a .script command with evaluated arguments",
         "void LegacyCommand(const string &in name, const ?&in ...)", "command {1} {...}"),
        ("a $function with evaluated arguments",
         "string LegacyFunction(const string &in name, const ?&in ...)", "function {1} {...}"),
    ]),
]


def param_decl(type_: str, name: str = "") -> str:
    """The AngelScript parameter for a mapping type. Entities take any value: a handle, an id or a
    name such as ent_lastseen."""
    if type_ == "...":
        return "const ?&in ..."
    decl = {"string": "const string &in", "text": "const string &in", "entity": "const ?&in",
            "Vector3": "const Vector3 &in"}.get(type_, type_)
    return f"{decl} {name}" if name else decl


def return_decl(type_: str) -> str:
    return {"entity": "string", "text": "string"}.get(type_, type_)


def without_variadic(decl: str, action: str) -> tuple[str, str] | None:
    """`f(a, const ?&in ...) | x {1} {...}` -> `f(a) | x {1}`: a variadic parameter needs at least
    one argument, so calls without any use this overload."""
    if not decl.endswith("const ?&in ...)"):
        return None
    head = decl[:-len("const ?&in ...)")].rstrip()
    head = head[:-1] if head.endswith(",") else head
    return head + ")", action.replace(" {...}", "")


def _command_lines() -> list[str]:
    lines: list[str] = []
    done: set[tuple[str, int]] = set()
    for name, spec in list(mapping.COMMANDS.items()) + list(mapping.ITEM_COMMANDS.items()):
        params = spec.params
        # a trailing text or variadic part may be left out (the handler then gets nothing for it)
        required = [p for p in params if not p.optional and not (p is params[-1] and p.type in ("text", "..."))]
        for count in range(len(required), len(params) + 1):
            used = params[:count]
            key = (spec.method, count)
            if key in done:
                continue
            done.add(key)
            decl = ", ".join(param_decl(p.type, p.name) for p in used)
            args = " ".join("{...}" if p.type == "..." else "{%d}" % i for i, p in enumerate(used, start=1))
            if not lines or not lines[-1].endswith(f"| command {name}" + (" " + args if args else ""))                     and f"| command {name}" not in lines[-1]:
                lines.append(f"// {name} - {spec.doc}")
            lines.append(f"void {spec.method}({decl}) | command {name}{' ' + args if args else ''}")
    return lines


def _function_lines() -> list[str]:
    lines: list[str] = []
    for name, spec in mapping.FUNCTIONS.items():
        if not spec.method or spec.template:
            continue
        engine_name = name.split("/")[0][1:]       # "$relpos/2": the two-argument form of $relpos
        decl = ", ".join(param_decl(t) for t in spec.params)
        if spec.components:
            args = " ".join("{1.%s}" % axis for axis in "xyz")
        else:
            args = " ".join("{%d}" % i for i in range(1, len(spec.params) + 1))
        lines.append(f"// ${engine_name}{' - ' + spec.doc if spec.doc else ''}")
        lines.append(f"{return_decl(spec.returns)} {spec.method}({decl}) | function {engine_name}"
                     f"{' ' + args if args else ''}")
    return lines


def _property_lines() -> list[str]:
    lines: list[str] = []
    done: set[str] = set()
    for prop, (method, type_) in mapping.GET_PROPERTIES.items():
        if method in done:
            continue        # isalive and alive are the same property
        done.add(method)
        lines.append(f"{return_decl(type_)} {method}(const ?&in entity) | function get {{1}} {prop}")
    for prop, (method, type_) in mapping.GET_PROPERTIES_ARG.items():
        lines.append(f"{return_decl(type_)} {method}(const ?&in entity, const ?&in name) "
                     f"| function get {{1}} {prop} {{2}}")
    for prefix, (method, type_) in mapping.GET_PREFIXED.items():
        lines.append(f"{return_decl(type_)} {method}(const ?&in entity, const string &in name) "
                     f"| function get {{1}} {prefix}{{2}}")
    return lines


def _value_lines() -> list[str]:
    lines: list[str] = []
    for command, (method, type_) in mapping.OUTPUT_COMMANDS.items():
        lines.append(f"// {command} <var> - the command writes its result into a variable")
        lines.append(f"{return_decl(type_)} {method}() | output {command}")
    for builtin, (code, type_) in mapping.BUILTINS.items():
        if code.endswith("()"):
            lines.append(f"{return_decl(type_)} {code[:-2]}() | eval {builtin}")
    return lines


def api_file() -> str:
    out = [GENERATED, "", HEADER]

    def section(title: str, lines: list[str]) -> None:
        out.extend(["", f"// ---- {title} " + "-" * max(4, 90 - len(title)), ""])
        out.extend(lines)

    for title, entries in GENERAL:
        lines = []
        for doc, decl, action in entries:
            lines.append(f"// {doc}")
            shorter = without_variadic(decl, action)
            if shorter:
                lines.append(f"{shorter[0]} | {shorter[1]}")
            lines.append(f"{decl} | {action}")
        section(title, lines)
    section("Commands", _command_lines())
    section("$functions", _function_lines())
    section("$get(<entity>,<property>)", _property_lines())
    section("Values", _value_lines())
    return "\n".join(out) + "\n"


def api_names() -> set[str]:
    """The names of every function in the table (no class or variable may use them)."""
    found = set()
    for line in api_file().splitlines():
        if "|" in line and not line.startswith("//"):
            found.add(line.split("(", 1)[0].split()[-1])
    return found


def write_runtime(out_root: Path) -> list[Path]:
    runtime = out_root / "runtime"
    runtime.mkdir(parents=True, exist_ok=True)
    path = runtime / "LegacyApi.txt"
    path.write_text(api_file(), encoding="utf-8", newline="\n")
    return [path]
