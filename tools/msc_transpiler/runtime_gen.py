"""Writes the typed wrappers in scripts/angelscript/runtime/ from mapping.py.

Commands.as  - mixin LegacyCommands: one method per .script command in mapping.COMMANDS
Functions.as - mixin LegacyFunctions: $functions, $get properties and game.* values

Every wrapper hands its arguments to the engine's own handler through ScriptHost, so it
behaves exactly like the .script line it replaces.
"""

from __future__ import annotations

from pathlib import Path

from . import mapping

GENERATED = "// Generated by msc_transpiler (runtime_gen.py) from mapping.py - edit mapping.py, not this file."


def _param_type(type_: str) -> str:
    return {"string": "const string &in", "text": "const string &in", "entity": "const string &in",
            "Vector3": "const Vector3 &in"}.get(type_, type_)


def _as_text(type_: str, name: str) -> str:
    return name if type_ in ("string", "text", "entity") else f"Text({name})"


def _from_text(type_: str, code: str) -> str:
    return {"int": f"Int({code})", "float": f"Float({code})", "bool": f"Truthy({code})",
            "Vector3": f"Vec({code})"}.get(type_, code)


def _ret_type(type_: str) -> str:
    return "string" if type_ in ("entity", "text") else type_


def commands_file() -> str:
    lines = ["#pragma context server", "", GENERATED, "",
             "// .script commands as methods of every converted script (see ScriptEntity).",
             "mixin class LegacyCommands", "{"]
    done: set[tuple[str, int]] = set()
    for name, spec in mapping.COMMANDS.items():
        params = spec.params
        required = [p for p in params if not p.optional]
        # one overload per number of optional parameters supplied
        for count in range(len(required), len(params) + 1):
            used = params[:count]
            key = (spec.method, count)
            if key in done:
                continue
            done.add(key)
            decl = ", ".join(f"{_param_type(p.type)} {p.name}" for p in used)
            args = ", ".join(_as_text(p.type, p.name) for p in used)
            lines.append("")
            lines.append(f"\t// {name} - {spec.doc}")
            lines.append(f"\tvoid {spec.method}({decl})")
            lines.append("\t{")
            lines.append(f'\t\thost.Command("{name}"{", { " + args + " }" if args else ""});')
            lines.append("\t}")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def functions_file() -> str:
    lines = ["#pragma context server", "", GENERATED, "",
             "// $functions, $get properties and game.* values for converted scripts.",
             "mixin class LegacyFunctions", "{"]
    for name, spec in mapping.FUNCTIONS.items():
        if not spec.method or spec.template:
            continue
        params = [(t, f"arg{i + 1}") for i, t in enumerate(spec.params)]
        decl = ", ".join(f"{_param_type(t)} {n}" for t, n in params)
        args = ", ".join(_as_text(t, n) for t, n in params)
        call = f'host.Function("{name[1:]}"{", { " + args + " }" if args else ""})'
        lines.append("")
        lines.append(f"\t// {name}{' - ' + spec.doc if spec.doc else ''}")
        lines.append(f"\t{_ret_type(spec.returns)} {spec.method}({decl})")
        lines.append("\t{")
        lines.append(f"\t\treturn {_from_text(spec.returns, call)};")
        lines.append("\t}")

    for prop, (method, type_) in mapping.GET_PROPERTIES.items():
        lines.append("")
        lines.append(f"\t// $get(<entity>,{prop})")
        lines.append(f"\t{_ret_type(type_)} {method}(const string &in entity)")
        lines.append("\t{")
        call = 'host.Function("get", { entity, "' + prop + '" })'
        lines.append(f"\t\treturn {_from_text(type_, call)};")
        lines.append("\t}")
    for prop, (method, type_) in mapping.GET_PROPERTIES_ARG.items():
        lines.append("")
        lines.append(f"\t// $get(<entity>,{prop},<name>)")
        lines.append(f"\t{_ret_type(type_)} {method}(const string &in entity, const string &in name)")
        lines.append("\t{")
        call = 'host.Function("get", { entity, "' + prop + '", name })'
        lines.append(f"\t\treturn {_from_text(type_, call)};")
        lines.append("\t}")

    for builtin, (code, type_) in mapping.BUILTINS.items():
        if not code.endswith("()"):
            continue
        lines.append("")
        lines.append(f"\t// {builtin}")
        lines.append(f"\t{_ret_type(type_)} {code[:-2]}()")
        lines.append("\t{")
        call = 'host.Eval("' + builtin + '")'
        lines.append(f"\t\treturn {_from_text(type_, call)};")
        lines.append("\t}")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_runtime(out_root: Path) -> list[Path]:
    runtime = out_root / "runtime"
    runtime.mkdir(parents=True, exist_ok=True)
    written = []
    for file_name, text in (("Commands.as", commands_file()), ("Functions.as", functions_file())):
        path = runtime / file_name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
